"""Regenerate numerical fixtures using Alex Rogozhnikov's Python Einops.

Development only; Rust users and `cargo test` do not need Python.

    python -m pip install einops==0.8.1 numpy==2.3.5
    python tools/generate_reference.py

The expected values come from the public Einops API, not copied implementation
code. Source: https://github.com/arogozhnikov/einops
"""

import json
from pathlib import Path

import einops
import numpy as np


def case(name, operation, shape, pattern, axes=None, reduction=None, values=None):
    tensor = np.asarray(
        values if values is not None else np.arange(np.prod(shape)), dtype=np.float32
    ).reshape(shape)
    axes = axes or {}
    if operation == "reduce":
        result = einops.reduce(tensor, pattern, reduction, **axes)
    else:
        result = getattr(einops, operation)(tensor, pattern, **axes)
    return {
        "name": name,
        "operation": operation,
        "input_shape": list(shape),
        "input": tensor.flatten().tolist(),
        "pattern": pattern,
        "axes": axes,
        "reduction": reduction,
        "output_shape": list(result.shape),
        "output": result.flatten().tolist(),
    }


cases = [
    case("transpose", "rearrange", [2, 3], "a b -> b a"),
    case("flatten", "rearrange", [2, 2, 3], "b h w -> b (h w)"),
    case("split", "rearrange", [2, 6], "b (h w) -> b h w", {"h": 2}),
    case("split_with_both_sizes", "rearrange", [6], "(h w) -> w h", {"h": 2, "w": 3}),
    case("attention_heads", "rearrange", [2, 3, 6], "b t (h d) -> b h t d", {"h": 2}),
    case("merged_transpose", "rearrange", [2, 3, 2], "a b c -> (c a) b"),
    case("space_to_depth", "rearrange", [1, 4, 4, 2], "b (h p) (w q) c -> b h w (c p q)", {"p": 2, "q": 2}),
    case("squeeze", "rearrange", [1, 2, 1, 3], "1 h 1 w -> h w"),
    case("unsqueeze", "rearrange", [2, 3], "h w -> 1 h w 1"),
    case("empty_groups", "rearrange", [1, 2, 3], "() h w -> h () w"),
    case("only_singletons", "rearrange", [1], "1 ... -> (...) 1", values=[7]),
    case("ellipsis_permute", "rearrange", [2, 3, 2], "... c -> c ..."),
    case("empty_ellipsis", "rearrange", [3], "... c -> c ..."),
    case("ellipsis_flatten", "rearrange", [2, 3, 2], "b ... -> b (...)"),
    case("sum", "reduce", [2, 3], "h w -> h", reduction="sum"),
    case("mean", "reduce", [2, 2, 3], "b h w -> b", reduction="mean"),
    case("min", "reduce", [2, 3], "h w -> h", reduction="min", values=[3, -2, 7, -5, 9, 1]),
    case("max", "reduce", [2, 3], "h w -> w", reduction="max", values=[3, -2, 7, -5, 9, 1]),
    case("product", "reduce", [2, 3], "h w -> h", reduction="prod", values=[2, -3, 4, -1, 5, 2]),
    case("pool", "reduce", [4, 4], "(h p) (w q) -> h w", {"p": 2, "q": 2}, "mean"),
    case("anonymous_pool", "reduce", [4, 4], "(h 2) (w 2) -> h w", reduction="max"),
    case("reduce_and_reorder", "reduce", [2, 3, 2], "a b c -> c a", reduction="sum"),
    case("reduce_keepdims", "reduce", [2, 3, 2], "a b c -> 1 b 1", reduction="mean"),
    case("reduce_all_to_singleton", "reduce", [2, 3], "h w -> 1", reduction="sum"),
    case("reduce_ellipsis", "reduce", [2, 3, 2], "... c -> c", reduction="sum"),
    case("reduce_empty_ellipsis", "reduce", [3], "... c -> c", reduction="mean"),
    case("repeat_channel", "repeat", [2, 3], "h w -> h w c", {"c": 2}),
    case("repeat_tile", "repeat", [3], "h -> (r h)", {"r": 2}),
    case("repeat_interleave", "repeat", [3], "h -> (h r)", {"r": 2}),
    case("repeat_reorder", "repeat", [2, 3], "h w -> c w h", {"c": 2}),
    case("repeat_two_axes", "repeat", [2, 2], "h w -> (h p) (w q)", {"p": 2, "q": 3}),
    case("repeat_anonymous", "repeat", [2, 3], "h w -> h w 2"),
    case("repeat_ellipsis", "repeat", [2, 3, 2], "... c -> ... (c r)", {"r": 2}),
]

lines = [
    "// Generated by tools/generate_reference.py; do not edit by hand.",
    "// Reference: https://github.com/arogozhnikov/einops (Alex Rogozhnikov).",
    f"// Einops {einops.__version__}, NumPy {np.__version__}, float32, C order.",
    "const FIXTURES: &[Fixture] = &[",
]
for fixture in cases:
    lines.append("    Fixture {")
    for key in ("name", "operation", "pattern"):
        lines.append(f"        {key}: {json.dumps(fixture[key])},")
    for key in ("input_shape", "input", "output_shape", "output"):
        lines.append(f"        {key}: &{fixture[key]!r},")
    axes = ", ".join(f"({json.dumps(k)}, {v})" for k, v in fixture["axes"].items())
    lines.append(f"        axes: &[{axes}],")
    reduction = (
        "None" if fixture["reduction"] is None
        else f"Some({json.dumps(fixture['reduction'])})"
    )
    lines.append(f"        reduction: {reduction},")
    lines.append("    },")
lines.append("];")
destination = Path(__file__).resolve().parents[1] / "tests/fixtures/einops.rs"
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote {len(cases)} fixtures to {destination}")
